#!/usr/bin/env node
/**
 * Configure Sensory TrulyNatural SDK paths and copy the Hey Ruby .snsr model into the app.
 *
 * Prerequisites:
 * 1. License + SDK from https://www.sensory.com (TrulyNatural / TrulyHandsfree)
 * 2. Custom phrase-spot model file hey_ruby.snsr from Sensory (PHRASESPOT task)
 *
 * Usage:
 *   SNSR_ROOT=~/Sensory/TrulyNaturalSDK/7.7.0 npm run setup:sensory
 *   SNSR_ROOT=... npm run setup:sensory -- --model /path/to/hey_ruby.snsr
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const androidGradleProps = path.join(root, 'android', 'gradle.properties');
const iosXcconfig = path.join(root, 'ios', 'App', 'sensory.xcconfig');
const modelName = 'hey_ruby.snsr';

function parseArgs() {
  const args = process.argv.slice(2);
  let modelPath = process.env.SENSORY_MODEL_PATH || '';
  for (let i = 0; i < args.length; i++) {
    if (args[i] === '--model' && args[i + 1]) {
      modelPath = args[i + 1];
      i++;
    }
  }
  return { modelPath };
}

function upsertGradleProperty(content, key, value) {
  const line = `${key}=${value}`;
  const re = new RegExp(`^${key}=.*$`, 'm');
  if (re.test(content)) return content.replace(re, line);
  return `${content.trimEnd()}\n${line}\n`;
}

function main() {
  const snsrRoot = (process.env.SNSR_ROOT || '').replace(/^~/, process.env.HOME || '');
  const snsrVersion = process.env.SNSR_LIB_VERSION || '7.7.0';
  const { modelPath } = parseArgs();

  if (!snsrRoot) {
    console.error(
      'Set SNSR_ROOT to your TrulyNatural SDK install directory, e.g.\n' +
        '  SNSR_ROOT=~/Sensory/TrulyNaturalSDK/7.7.0 npm run setup:sensory'
    );
    process.exit(1);
  }

  if (!fs.existsSync(snsrRoot)) {
    console.error(`SNSR_ROOT does not exist: ${snsrRoot}`);
    process.exit(1);
  }

  const m2 = path.join(snsrRoot, 'm2repository');
  if (!fs.existsSync(m2)) {
    console.warn(`Warning: m2repository not found at ${m2} — check SDK version/path`);
  }

  let gradle = fs.existsSync(androidGradleProps)
    ? fs.readFileSync(androidGradleProps, 'utf8')
    : '';
  gradle = upsertGradleProperty(gradle, 'sensory.enabled', 'true');
  gradle = upsertGradleProperty(gradle, 'snsr.root', snsrRoot);
  gradle = upsertGradleProperty(gradle, 'snsr.lib.version', snsrVersion);
  gradle = upsertGradleProperty(gradle, 'snsr.lib.type', 'tnl');
  fs.writeFileSync(androidGradleProps, gradle);
  console.log(`Updated ${path.relative(root, androidGradleProps)}`);

  const xcconfig = [
    '// Generated by npm run setup:sensory — do not commit if it contains machine-specific paths',
    `SNSR_ROOT = ${snsrRoot}`,
    'HEADER_SEARCH_PATHS = $(inherited) $(SNSR_ROOT)/include',
    'LIBRARY_SEARCH_PATHS = $(inherited) $(SNSR_ROOT)/lib/ios',
    'OTHER_LDFLAGS = $(inherited) -lsnsr -framework Accelerate -framework AudioToolbox',
    '',
  ].join('\n');
  fs.writeFileSync(iosXcconfig, xcconfig);
  console.log(`Wrote ${path.relative(root, iosXcconfig)}`);
  console.log(
    'In Xcode: select the App target → Build Settings → include sensory.xcconfig (or merge paths manually).'
  );

  const androidAssetDir = path.join(root, 'android', 'app', 'src', 'main', 'assets', 'sensory');
  const iosAppDir = path.join(root, 'ios', 'App', 'App');
  fs.mkdirSync(androidAssetDir, { recursive: true });

  if (modelPath) {
    if (!fs.existsSync(modelPath)) {
      console.error(`Model file not found: ${modelPath}`);
      process.exit(1);
    }
    fs.copyFileSync(modelPath, path.join(androidAssetDir, modelName));
    fs.copyFileSync(modelPath, path.join(iosAppDir, modelName));
    console.log(`Copied ${modelName} to Android assets and iOS App bundle`);
  } else {
    console.log(
      `Optional: copy your Sensory model with\n` +
        `  npm run setup:sensory -- --model /path/to/${modelName}`
    );
  }

  console.log('\nNext steps:');
  console.log('  1. Set VITE_WAKE_ENGINE=sensory (or auto) in .env');
  console.log('  2. npm run build && npx cap sync');
  console.log('  3. Open Xcode/Android Studio and build on device (microphone required)');
}

main();
